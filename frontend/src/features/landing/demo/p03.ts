export type DemoTone = 'behind' | 'outline' | 'caution'

export interface DemoBox {
  label: string
  /** Уверенность детектора. */
  conf: number
  /** Левый верхний и правый нижний углы в долях кадра. */
  box: [number, number, number, number]
}

export interface DemoFrame {
  src: string
  /** Дата на штампе кадра. */
  date: string
  alt: string
  boxes: DemoBox[]
}

export interface DemoFinding {
  id: string
  title: string
  /** Что стоит в колонке «Статус». */
  status: string
  tone: DemoTone
  /** Короткая строка для списка. */
  plan: string
  fact: string
  /** Важность отклонения. */
  severity: 'Критично' | 'Внимание'
  hypothesis: boolean
  expected: string
  observed: string
  confidence: string
  confidenceReason: string
  rule: string
  ruleSource: string
  cannotClaim: string
  frames: DemoFrame[]
}

